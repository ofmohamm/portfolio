"""Generate the footer's bamboo stand (Kabini dry-deciduous theme) as an Astro
component. Deterministic (fixed seed). Culms rise from the bottom edge and end
in leaf sprays inside the strip, so nothing is cut off at the top.

    python3 -I design/art/bamboo.py        (from the repo root)
"""
import math, random, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / 'src/components/forest/Bamboo.astro'
random.seed(11)

W, H = 1200, 210
CULM = ['#8C9440', '#7E8A3A', '#98A04A', '#86903E']
NODE = '#5E6428'
LEAF = ['#6F8436', '#7E8E3C', '#8E9B3F', '#A2A84A', '#B3AE5A', '#5F7A33']
f = lambda v: f'{v:.1f}'


def blade(x, y, ang, L):
    """Narrow lanceolate bamboo leaf from (x, y) along ang."""
    wd = L * 0.12
    d = (math.cos(ang), math.sin(ang)); n = (-d[1], d[0])
    P = lambda a, b: (x + a * d[0] + b * n[0], y + a * d[1] + b * n[1])
    tip = P(L, 0)
    c1, c2, c3, c4 = P(.18 * L, wd), P(.7 * L, .75 * wd), P(.7 * L, -.75 * wd), P(.18 * L, -wd)
    return (f'M{f(x)} {f(y)}C{f(c1[0])} {f(c1[1])} {f(c2[0])} {f(c2[1])} {f(tip[0])} {f(tip[1])}'
            f'C{f(c3[0])} {f(c3[1])} {f(c4[0])} {f(c4[1])} {f(x)} {f(y)}Z')


def quad(p0, p1, p2, t):
    u = 1 - t
    x = u * u * p0[0] + 2 * u * t * p1[0] + t * t * p2[0]
    y = u * u * p0[1] + 2 * u * t * p1[1] + t * t * p2[1]
    dx = 2 * u * (p1[0] - p0[0]) + 2 * t * (p2[0] - p1[0])
    dy = 2 * u * (p1[1] - p0[1]) + 2 * t * (p2[1] - p1[1])
    return x, y, math.atan2(dy, dx)


def spray(x, y, dirx, size, alpha):
    """A twig with a fan of drooping leaves, the way bamboo holds them."""
    tx, ty = x + dirx * size * 0.55, y - size * 0.12
    k = random.randint(3, 6)
    base = 0.3 if dirx > 0 else math.pi - 0.3
    parts = [f'<path d="M{f(x)} {f(y)}Q{f((x + tx) / 2)} {f(y - size * .2)} {f(tx)} {f(ty)}" stroke="{NODE}" stroke-width="1" fill="none"/>']
    for j in range(k):
        a = base + dirx * (j - k / 2) * 0.3 + random.uniform(-0.1, 0.1)
        parts.append(f'<path d="{blade(tx, ty, a, size * random.uniform(.8, 1.15))}" fill="{random.choice(LEAF)}" fill-opacity="{alpha * random.uniform(.8, .95):.2f}"/>')
    delay = -random.uniform(0, 6)
    return f'<g class="spray" style="transform-origin:{f(x)}px {f(y)}px;animation-delay:{delay:.2f}s">' + ''.join(parts) + '</g>'


def culm(x0, height, lean, width, alpha):
    p0 = (x0, H + 6)
    p2 = (x0 + lean * height, H - height)
    p1 = (x0 + lean * height * 0.2, H - height * 0.55)
    # tapered body
    steps, left, right = 16, [], []
    for i in range(steps + 1):
        t = i / steps
        x, y, a = quad(p0, p1, p2, t)
        w = width * (1 - 0.65 * t) / 2
        nx, ny = -math.sin(a), math.cos(a)
        left.append((x + nx * w, y + ny * w)); right.append((x - nx * w, y - ny * w))
    pts = left + right[::-1]
    body = 'M' + 'L'.join(f'{f(x)} {f(y)}' for x, y in pts) + 'Z'
    col = random.choice(CULM)
    parts = [f'<path d="{body}" fill="{col}" fill-opacity="{alpha:.2f}"/>']
    # nodes, and sprays from the upper nodes
    nodes = max(3, int(height / 26))
    for i in range(1, nodes):
        t = i / nodes
        x, y, a = quad(p0, p1, p2, t)
        w = width * (1 - 0.65 * t) / 2 + 0.8
        nx, ny = -math.sin(a), math.cos(a)
        parts.append(f'<path d="M{f(x + nx * w)} {f(y + ny * w)}L{f(x - nx * w)} {f(y - ny * w)}" stroke="{NODE}" stroke-width="1.3" stroke-opacity="{alpha * .8:.2f}"/>')
        if t > 0.35 and random.random() < 0.55:
            parts.append(spray(x, y, random.choice((-1, 1)), random.uniform(20, 30), alpha))
    tx, ty, _ = quad(p0, p1, p2, 1)
    parts.append(spray(tx, ty, 1 if lean >= 0 else -1, random.uniform(22, 30), alpha))
    delay = -random.uniform(0, 10)
    return f'<g class="culm" style="transform-origin:{f(x0)}px {H}px;animation-delay:{delay:.2f}s">' + ''.join(parts) + '</g>'


# Clumps across the width, back row lighter for depth.
groups = []
x = random.uniform(-20, 30)
while x < W + 30:
    culms = random.randint(3, 6)
    for k in range(culms):
        back = random.random() < 0.35
        h = random.uniform(95, 190) * (0.85 if back else 1)
        groups.append((back, culm(x + random.uniform(-14, 14), h, random.uniform(-0.28, 0.28),
                                  random.uniform(4.5, 7.5), 0.45 if back else 0.95)))
    x += random.uniform(110, 190)
groups.sort(key=lambda g: not g[0])   # back row first

svg = (f'<svg viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMax slice" aria-hidden="true" focusable="false">'
       + ''.join(g for _, g in groups) + '</svg>')
OUT.write_text('---\n// Generated by design/art/bamboo.py (seeded, deterministic). Footer bamboo stand.\n---\n' + svg + '\n')
print('wrote', OUT.relative_to(ROOT), len(svg), 'bytes,', len(groups), 'culms')
